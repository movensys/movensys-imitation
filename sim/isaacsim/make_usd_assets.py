"""Write the standalone USD assets of the PushT scene: the T block and the pusher tip.

Run from the project venv (``pip install -e '.[sim]'`` adds ``usd-core``) or with Isaac Sim's
Python, which has ``pxr`` once its app is up:

    python sim/isaacsim/make_usd_assets.py
    ~/isaac-sim/python.sh sim/isaacsim/make_usd_assets.py

Writes into ``sim/isaacsim/assets/`` (ASCII-encoded ``.usd`` so diffs stay readable):

* ``t_block.usd``      rigid T: gym-pusht proportions at 40 mm per unit, 30 mm tall, 0.25 kg,
                       dark blue (20, 40, 110), friction 0.40/0.35. Default prim ``/t_block``.
* ``pusher_tip.usd``   20 mm cylinder, collision only (it rides on the link it is parented to).
                       Default prim ``/pusher_tip``.

Both carry their materials under ``<root>/Looks`` and have a default prim, so a scene references
them whole::

    stage.DefinePrim("/World/pusht/t_block").GetReferences().AddReference("./assets/t_block.usd")
    stage.DefinePrim(".../Link6/pusher_tip").GetReferences().AddReference("./assets/pusher_tip.usd")

Frames
------
* T block: origin at the *bar-stem junction* on the bottom face, the same convention as the
  ``/pusht/t_block/pose`` topic and ``geometry.py``: at yaw 0 the bar runs along +x on the +y
  side and the stem extends toward -y; the block sits on z = 0.
* Pusher tip: origin at the *mount face*, the cylinder extends along +z for ``--tip-length``.
  Under ``Link6`` the mount face is 0.14 m along +z (the end of the gripper body), so the asset is
  placed with translate (0, 0, 0.14) and the tip bottom lands at 0.14 + length = 0.22 m.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from movensys_imitation.tasks.pusht import geometry as g  # noqa: E402

try:
    from pxr import Gf, Kind, Sdf, Usd, UsdGeom, UsdPhysics, UsdShade
except ModuleNotFoundError:  # Isaac Sim's Python only exposes pxr after the app starts
    from isaacsim import SimulationApp

    _app = SimulationApp({"headless": True})
    from pxr import Gf, Kind, Sdf, Usd, UsdGeom, UsdPhysics, UsdShade

ASSETS = Path(__file__).resolve().parent / "assets"

BLOCK_RGB = (20, 40, 110)  # dark blue T
TIP_RGB = (0.15, 0.15, 0.18)
TIP_RADIUS = 0.010


def new_stage(path: Path, doc: str) -> Usd.Stage:
    path.unlink(missing_ok=True)
    layer = Sdf.Layer.CreateNew(str(path), args={"format": "usda"})
    layer.documentation = doc
    stage = Usd.Stage.Open(layer)
    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(stage, 1.0)
    UsdPhysics.SetStageKilogramsPerUnit(stage, 1.0)
    return stage


def set_xform(prim, translate=(0, 0, 0), orient: Gf.Quatf | None = None, scale=(1, 1, 1)):
    xf = UsdGeom.Xformable(prim)
    xf.ClearXformOpOrder()
    xf.AddTranslateOp(UsdGeom.XformOp.PrecisionDouble).Set(Gf.Vec3d(*translate))
    xf.AddOrientOp(UsdGeom.XformOp.PrecisionFloat).Set(orient or Gf.Quatf(1, 0, 0, 0))
    xf.AddScaleOp(UsdGeom.XformOp.PrecisionFloat).Set(Gf.Vec3f(*scale))


def color_material(stage, path: str, rgb) -> UsdShade.Material:
    mat = UsdShade.Material.Define(stage, path)
    surf = UsdShade.Shader.Define(stage, f"{path}/surface")
    surf.CreateIdAttr("UsdPreviewSurface")
    surf.CreateInput("diffuseColor", Sdf.ValueTypeNames.Color3f).Set(Gf.Vec3f(*rgb))
    surf.CreateInput("roughness", Sdf.ValueTypeNames.Float).Set(0.7)
    surf.CreateInput("metallic", Sdf.ValueTypeNames.Float).Set(0.0)
    mat.CreateSurfaceOutput().ConnectToSource(
        surf.CreateOutput("surface", Sdf.ValueTypeNames.Token)
    )
    return mat


def physics_material(stage, path: str, static: float, dynamic: float) -> UsdShade.Material:
    mat = UsdShade.Material.Define(stage, path)
    api = UsdPhysics.MaterialAPI.Apply(mat.GetPrim())
    api.CreateStaticFrictionAttr(static)
    api.CreateDynamicFrictionAttr(dynamic)
    api.CreateRestitutionAttr(0.0)
    return mat


def bind(prim, material: UsdShade.Material, purpose: str = ""):
    api = UsdShade.MaterialBindingAPI.Apply(prim)
    if purpose:
        api.Bind(material, UsdShade.Tokens.weakerThanDescendants, purpose)
    else:
        api.Bind(material)


def make_t_block(path: Path) -> None:
    stage = new_stage(
        path,
        "PushT T block (plan Section 5): gym-pusht proportions, origin at the bar-stem junction "
        "on the bottom face, yaw 0 = bar along +x on the +y side. Generated by make_usd_assets.py.",
    )
    root = UsdGeom.Xform.Define(stage, "/t_block")
    prim = root.GetPrim()
    stage.SetDefaultPrim(prim)
    Usd.ModelAPI(prim).SetKind(Kind.Tokens.component)
    set_xform(prim)
    UsdPhysics.RigidBodyAPI.Apply(prim)
    # Authored velocities: the teleport graph in the scene writes to these attributes.
    UsdPhysics.RigidBodyAPI(prim).CreateVelocityAttr(Gf.Vec3f(0, 0, 0))
    UsdPhysics.RigidBodyAPI(prim).CreateAngularVelocityAttr(Gf.Vec3f(0, 0, 0))
    UsdPhysics.MassAPI.Apply(prim).CreateMassAttr(g.BLOCK_MASS)
    prim.SetCustomDataByKey("pusht:unit_m", g.UNIT)
    prim.SetCustomDataByKey("pusht:bar_xy_m", Gf.Vec2d(*g.BAR))
    prim.SetCustomDataByKey("pusht:stem_xy_m", Gf.Vec2d(*g.STEM))
    prim.SetCustomDataByKey("pusht:height_m", g.BLOCK_HEIGHT)
    prim.SetCustomDataByKey("pusht:centroid_local_m", Gf.Vec2d(*g.block_centroid_local()))
    prim.SetCustomDataByKey("pusht:rgb", Gf.Vec3i(*BLOCK_RGB))

    UsdGeom.Scope.Define(stage, "/t_block/Looks")
    vis = color_material(stage, "/t_block/Looks/block_material", [c / 255 for c in BLOCK_RGB])
    phys = physics_material(stage, "/t_block/Looks/block_physics", 0.40, 0.35)

    h = g.BLOCK_HEIGHT
    for name, size, centre in (
        ("bar", (g.BAR[0], g.BAR[1], h), (0.0, g.BAR[1] / 2, h / 2)),
        ("stem", (g.STEM[0], g.STEM[1], h), (0.0, -g.STEM[1] / 2, h / 2)),
    ):
        cube = UsdGeom.Cube.Define(stage, f"/t_block/{name}")
        cube.CreateSizeAttr(1.0)
        cube.CreateExtentAttr([Gf.Vec3f(-0.5, -0.5, -0.5), Gf.Vec3f(0.5, 0.5, 0.5)])
        set_xform(cube.GetPrim(), centre, None, size)
        UsdPhysics.CollisionAPI.Apply(cube.GetPrim())
        bind(cube.GetPrim(), vis)
        bind(cube.GetPrim(), phys, "physics")
    stage.GetRootLayer().Save()


def make_pusher_tip(path: Path, length: float) -> None:
    stage = new_stage(
        path,
        "PushT pusher tip: a cylinder along +z from the mount face (origin) to the tip bottom at "
        f"z = {length} m. Collision only; it belongs to the rigid link it is parented under. "
        "Generated by make_usd_assets.py.",
    )
    root = UsdGeom.Xform.Define(stage, "/pusher_tip")
    prim = root.GetPrim()
    stage.SetDefaultPrim(prim)
    Usd.ModelAPI(prim).SetKind(Kind.Tokens.component)
    set_xform(prim)
    prim.SetCustomDataByKey("pusht:radius_m", TIP_RADIUS)
    prim.SetCustomDataByKey("pusht:length_m", length)
    prim.SetCustomDataByKey("pusht:link6_mount_z_m", 0.14)

    UsdGeom.Scope.Define(stage, "/pusher_tip/Looks")
    vis = color_material(stage, "/pusher_tip/Looks/tip_material", TIP_RGB)
    phys = physics_material(stage, "/pusher_tip/Looks/tip_physics", 0.30, 0.25)

    cyl = UsdGeom.Cylinder.Define(stage, "/pusher_tip/geom")
    cyl.CreateRadiusAttr(TIP_RADIUS)
    cyl.CreateHeightAttr(length)
    cyl.CreateAxisAttr(UsdGeom.Tokens.z)
    r = TIP_RADIUS
    cyl.CreateExtentAttr([Gf.Vec3f(-r, -r, -length / 2), Gf.Vec3f(r, r, length / 2)])
    set_xform(cyl.GetPrim(), (0.0, 0.0, length / 2))
    UsdPhysics.CollisionAPI.Apply(cyl.GetPrim())
    bind(cyl.GetPrim(), vis)
    bind(cyl.GetPrim(), phys, "physics")
    stage.GetRootLayer().Save()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out-dir", type=Path, default=ASSETS)
    parser.add_argument(
        "--tip-length", type=float, default=0.08, help="pusher tip cylinder length [m]"
    )
    args = parser.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    make_t_block(args.out_dir / "t_block.usd")
    make_pusher_tip(args.out_dir / "pusher_tip.usd", args.tip_length)
    print(f"wrote {args.out_dir / 't_block.usd'}")
    print(f"wrote {args.out_dir / 'pusher_tip.usd'} (length {args.tip_length} m)")


if __name__ == "__main__":
    main()
